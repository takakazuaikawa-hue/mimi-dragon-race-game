// 解禁条件のヒント（ロック時に図鑑・龍舎で表示）
const DRAGON_LORE_HINTS = ["スカウトで出会うと解禁", "交渉で心を開きかけると解禁", "仲間に迎えると解禁"];
const DRAGON_LORE_TITLES = ["断章 I 「出会いの噂」", "断章 II 「島の逸話」", "断章 III 「伝承の真相」"];

function dragonLoreTexts(id) { return DRAGON_LORE[id] || null; }
function dragonLoreLv(id) {
  try { return (state.player.collection && state.player.collection[id] && state.player.collection[id].loreLv) || 0; }
  catch (e) { return 0; }
}
// lv(1-3)まで解禁。新規に開いた場合はそのテキストを返す（演出用）。既読/対象外は null。
function dragonLoreUnlock(id, lv) {
  const L = DRAGON_LORE[id]; if (!L) return null;
  const e = (typeof poroColEntry === "function") ? poroColEntry(id) : null; if (!e) return null;
  if ((e.loreLv || 0) >= lv) return null;
  e.loreLv = lv;
  if (typeof saveGame === "function") saveGame();
  return L[lv - 1] || null;
}
// 図鑑用の収集統計。
function dragonLoreStats() {
  let got = 0, total = 0;
  for (const id in DRAGON_LORE) {
    total += 3;
    got += Math.min(3, dragonLoreLv(id));
  }
  return { got, total };
}
