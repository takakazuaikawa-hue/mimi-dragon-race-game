// そのジャンルから1本引く。直近に出たものは避ける（同じ話を続けて聞かされない）。
function scoutTopicPick(genre, recentTexts) {
  const pool = SCOUT_TOPICS.filter(x => x.g === genre);
  if (!pool.length) return null;
  const recent = recentTexts || [];
  const fresh = pool.filter(x => recent.indexOf(x.t) < 0);
  const use = fresh.length ? fresh : pool;
  return use[Math.floor(Math.random() * use.length)];
}

