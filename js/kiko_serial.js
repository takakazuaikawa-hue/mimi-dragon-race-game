// ── コースの記録（地域ごとの出走・的中・さいごに見た一着）────────────────
//   state.player.kikoCourse = { "<地域名>": { n: 出走, hit: 的中, last: さいごに見た一着の名前 } }
//   ★レースが確定した“あと”に、結果を写し取るだけ（ui_render.js settleRace の紀行ブロックから呼ぶ）。
//     着順・オッズ・配当・コインには一切触れない。連載の条件と、記事面の「このコースでのわたし」に使う。
//   この更新より前に走ったぶんは記録が無い＝ここから数えはじめる（古いセーブも壊れない）。
function kikoCourseNote(race, hit, winnerName) {
  try {
    var p = _ksP(); if (!race || !race.region) return;
    var all = p.kikoCourse || (p.kikoCourse = {});
    var c = all[race.region] || (all[race.region] = { n: 0, hit: 0, last: "" });
    c.n = (c.n || 0) + 1;
    if (hit) c.hit = (c.hit || 0) + 1;
    if (winnerName) c.last = String(winnerName);
  } catch (e) {}
}
function kikoCourseOf(region) {
  try { var c = (_ksP().kikoCourse || {})[region]; return { n: (c && c.n) || 0, hit: (c && c.hit) || 0, last: (c && c.last) || "" }; }
  catch (e) { return { n: 0, hit: 0, last: "" }; }
}
// その地域のレースが開くランク（いちばん低いもの）。データが無ければ 1。
function _ksRegionRank(region) {
  try {
    var m = 99;
    RACES.forEach(function (r) { if (r.region === region && r.rank < m) m = r.rank; });
    return m === 99 ? 1 : m;
  } catch (e) { return 1; }
}
// コースの回の条件：key="n"（出走）／"hit"（的中）を need 回。足りないぶんだけ「あと◯◯」で返す。
//   まだランクが足りずその地域を走れないときは、先にそれを言う（走れないのに「走れ」と言わない）。
function _ksCourseNeed(region, key, need) {
  var nm = String(region).replace(/地域$/, "");
  var rk = _ksRegionRank(region), my = _ksP().rank || 1;
  if (my < rk) return ["🏅 ランク" + rk + "で、" + nm + "のレースが開く"];
  var c = kikoCourseOf(region), have = (key === "hit") ? c.hit : c.n;
  if (have >= need) return [];
  if (key === "hit") return ["🎯 " + nm + "のレースで当てる" + (need > 1 ? "（あと" + (need - have) + "回）" : "")];
  return ["🏁 " + nm + "のレースを走る" + (need > 1 ? "（あと" + (need - have) + "戦）" : "")];
}
