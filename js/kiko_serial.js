// 状態（state.player.kikoSerial）：{ done: { 回id: 書いたときの通算レース数 }, last: 最後に書いたときのレース数, unread: 回id }
// =========================================================================
function kikoSerialData() {
  var p = _ksP();
  if (!p.kikoSerial || typeof p.kikoSerial !== "object") p.kikoSerial = { done: {}, last: null };
  if (!p.kikoSerial.done) p.kikoSerial.done = {};
  return p.kikoSerial;
}
function kikoSerialById(id) { for (var i = 0; i < KIKO_SERIAL.length; i++) if (KIKO_SERIAL[i].id === id) return KIKO_SERIAL[i]; return null; }
function kikoSerialNo(id) { for (var i = 0; i < KIKO_SERIAL.length; i++) if (KIKO_SERIAL[i].id === id) return i + 1; return 0; }
function kikoSerialDone(id) { try { return kikoSerialData().done[id] != null; } catch (e) { return false; } }
function kikoSerialDoneCount() { var n = 0; for (var i = 0; i < KIKO_SERIAL.length; i++) if (kikoSerialDone(KIKO_SERIAL[i].id)) n++; return n; }

// 取材先のスポット情報（地名・写真・エリア）。地図側が未読込でも落ちない。
function kikoSerialSpot(ep) {
  var s = null, area = null;
  try { s = (typeof KONRON_SPOTS !== "undefined") ? KONRON_SPOTS[ep.spot] : null; } catch (e) {}
  try { area = (typeof _kmAreaOf === "function") ? _kmAreaOf(ep.spot) : null; } catch (e) {}
  return {
    name: (s && s.name) || "島のどこか",
    photo: (s && s.photo) || "images/konron/island_aerial.webp",
    area: (area && area.name) || "崑崙島",
    tier: (s && s.tier) || 0
  };
}

// 次に書く回と、その状態。全部書き終えていれば null。
//   ready … いますぐ書ける（direct）／取材に行ける（!direct）
//   needs … 足りないものだけ（空なら ready）
function kikoSerialNext() {
  try {
    var d = kikoSerialData(), ep = null, idx = -1;
    for (var i = 0; i < KIKO_SERIAL.length; i++) if (d.done[KIKO_SERIAL[i].id] == null) { ep = KIKO_SERIAL[i]; idx = i; break; }
    if (!ep) return null;
    var needs = [];
    try { needs = (ep.need() || []).slice(); } catch (e) { needs = ["……"]; }
    if (!ep.direct) {
      // 島へ出られるか（＝初勝利）→ その場所まで行けるか（＝スポットの解放段）
      var mapOpen = false; try { mapOpen = (typeof konronMapUnlocked === "function") && konronMapUnlocked(); } catch (e) {}
      if (!mapOpen) { if (!needs.length) needs.push("🏆 はじめて勝って、島へ出られるようになる"); }
      else {
        var sp = null; try { sp = KONRON_SPOTS[ep.spot]; } catch (e) {}
        var open = true; try { open = !sp || _kmSpotOpen(sp); } catch (e) { open = false; }
        if (!open) {
          var at = 0; try { at = KM_TIER_AT[sp.tier] || 0; } catch (e) {}
          var rest = Math.max(0, at - _ksPeak());
          needs.push("💰 " + kikoSerialSpot(ep).name + "まで行けるようになる（総資産 あと" + _ksAmt(rest) + "）");
        }
      }
    }
    // 1回書いたら、次は1戦走ってから（題材は、暮らしのなかでたまる）
    var paced = (d.last == null) || (_ksRaces() > d.last);
    if (!needs.length && !paced) needs.push("🏁 次の取材は、もう1戦走ってから");
    return { ep: ep, idx: idx, no: idx + 1, ready: needs.length === 0, needs: needs };
  } catch (e) { return null; }
}
function kikoSerialReady() { var n = kikoSerialNext(); return !!(n && n.ready); }
// このスポットで、いま書ける回（無ければ null）。地図のスポット画面が呼ぶ。
function kikoSerialReadyAt(spotId) {
  var n = kikoSerialNext();
  return (n && n.ready && n.ep.spot === spotId) ? n : null;
}
// 取材先として待っている回（条件が未達でも、行き先としては教える）。地図の印に使う。
// 次の回がコースの回で、まだ条件が足りないとき＝「その地域で走ると書ける」をレース選択に知らせる。
function kikoSerialCourseTarget() {
  try {
    var n = kikoSerialNext();
    if (!n || !n.ep.region || n.ready) return null;
    // ランク不足や「もう1戦」だけが残っている時は、地域を名指ししても押せるものが無い
    if ((_ksP().rank || 1) < _ksRegionRank(n.ep.region)) return null;
    var own = []; try { own = n.ep.need() || []; } catch (e) { own = []; }
    if (!own.length) return null;
    return { region: n.ep.region, no: n.no, text: own[0] };
  } catch (e) { return null; }
}
function kikoSerialTargetSpot() { var n = kikoSerialNext(); return n ? n.ep.spot : null; }

// 書く。成功で回を返す（条件が欠けていれば null＝何も変えない）。
function kikoSerialWrite(id) {
  try {
    var n = kikoSerialNext();
    if (!n || !n.ready || n.ep.id !== id) return null;
    var d = kikoSerialData();
    d.done[id] = _ksRaces();
    d.last = _ksRaces();
    d.fresh = id;                       // 読み終えるまで🆕（一覧で印を付ける）
    try { if (typeof saveGame === "function") saveGame(); } catch (e) {}
    return n.ep;
  } catch (e) { return null; }
}
function kikoSerialMarkRead(id) {
  try { var d = kikoSerialData(); if (d.fresh === id) { d.fresh = null; if (typeof saveGame === "function") saveGame(); } } catch (e) {}
}

// 読者の声（回ごとに書き下ろし）。fav は記事と同じ作法で決定的に。
function kikoSerialComments(ep) {
  var out = [];
  try {
    var fol = _ksFol();
    (ep.cmts || []).forEach(function (c, i) {
      var v = KS_VOICES[c[0]]; if (!v) return;
      var seed = i * 7919, s = ep.id + v.h;
      for (var k = 0; k < s.length; k++) seed = (seed * 31 + s.charCodeAt(k)) >>> 0;
      out.push({ h: v.h, n: v.n, ic: v.ic, t: c[1], fav: 5 + (seed % Math.max(14, Math.floor(fol / 50))) });
    });
  } catch (e) {}
  return out;
}

