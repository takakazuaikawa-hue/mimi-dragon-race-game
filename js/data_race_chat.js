// プールから1件引く（{D} は賭け竜名に置換。竜名が無い場合はその行を避ける）
function rcChatPick(key, dragonName) {
  const pool = RC_CHAT[key] || RC_CHAT.idle;
  if (!pool || !pool.length) return null;
  const usable = dragonName ? pool : pool.filter(t => t.indexOf("{D}") < 0);
  if (!usable.length) return null;
  const t = usable[Math.floor(Math.random() * usable.length)];
  return dragonName ? t.replace(/\{D\}/g, dragonName) : t;
}
function rcChatHandle() {
  return RC_CHAT_HANDLES[Math.floor(Math.random() * RC_CHAT_HANDLES.length)];
}
