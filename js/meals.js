// 進捗（表示専用メタ）：食べた/解いたを記録。
function mealData() {
  var p = state.player;
  if (!p.meals) p.meals = {};
  if (!p.meals.eaten) p.meals.eaten = {};
  if (!p.meals.solved) p.meals.solved = {};
  return p.meals;
}
function mealsByTier(tierId) { return MEALS.filter(function (m) { return m.tier === tierId; }); }
function mealEaten(id) { return !!mealData().eaten[id]; }
function mealSolved(id) { return !!mealData().solved[id]; }
// 開放済み＝eatは食べた、guessは正解した。
function mealUnlocked(m) { return m.quiz ? mealSolved(m.id) : mealEaten(m.id); }
function eatMeal(id) { var d = mealData(); if (!d.eaten[id]) { d.eaten[id] = true; if (typeof saveGame === "function") saveGame(); } }
function solveMeal(id) { var d = mealData(); if (!d.solved[id]) { d.solved[id] = true; if (typeof saveGame === "function") saveGame(); } }
function mealTierStats(tierId) {
  var list = mealsByTier(tierId), got = 0;
  for (var i = 0; i < list.length; i++) if (mealUnlocked(list[i])) got++;
  return { got: got, total: list.length };
}
function mealStatsAll() {
  var got = 0;
  for (var i = 0; i < MEALS.length; i++) if (mealUnlocked(MEALS[i])) got++;
  return { got: got, total: MEALS.length };
}
