// いま解説席に座れる人（門番を通った人だけ）。fail-closed。
function availableCommentators() {
  return RACE_COMMENTATORS.filter(c => {
    try { return !!c.gate(); } catch (e) { return false; }
  });
}

// このレースの解説者を1人選ぶ（基本ランダム）。
// ★同じ人が続くと「毎回同じ番組」に見えるので、直前と同じ人は1回だけ引き直す（連続を減らすだけで禁止はしない）。
function pickCommentator(lastKey) {
  const pool = availableCommentators();
  if (!pool.length) return null;                     // fail-closed（誰も出せないなら解説なし）
  let pick = pool[Math.floor(Math.random() * pool.length)];
  if (pool.length > 1 && lastKey && pick.key === lastKey) {
    pick = pool[Math.floor(Math.random() * pool.length)];
  }
  return pick;
}
