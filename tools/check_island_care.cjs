'use strict';
const assert = require('node:assert/strict');
const D = require('../js/island_discovery.js'), C = require('../js/island_care.js');
const F = require('../js/shingan_festival.js'), R = require('../js/shingan_recovery.js');
const context = place => ({ enabled: true, currentSpotId: place, openSpots: ['market', 'tanada'], dragonLevel: 0 });
let found = D.observe(null, 'water_jars', context('market'));
found = D.observe(found, 'water_fork', context('tanada'));
found = D.propose(found, 'water', 'upstream', ['water_jars', 'water_fork'], context('tanada'));
found = D.inspect(found, 'water', 'trace', context('tanada'));
assert(D.exportDiscoveries(found).some(d => d.caseId === 'water'));
const p = { coins: 455, completedRaces: 7, islandDiscovery: found, island: { lv: { public: 0 } } };
const before = JSON.stringify(p), tx = C.purchase(p);
assert(tx.ok); assert.equal(tx.coins, 155); assert.equal(JSON.stringify(p), before);
const cared = { ...p, coins: tx.coins, islandCare: tx.care };
assert(C.paid(cared)); assert.equal(C.purchase(cared).ok, false);
assert.equal(C.purchase({ ...p, coins: 299 }).ok, false);
assert.equal(C.purchase({ ...p, islandDiscovery: null }).ok, false);
assert.equal(C.capture({ ...cared, islandDiscovery: null }), null);
assert.equal(C.capture({ ...p, islandCare: { version: 1, waterCarrier: { cost: 0 } } }), null);
const a = F.capture(p), b = F.capture(cared);
assert.equal(a.care, null); assert.equal(b.care.waterCarrier.cost, 300);
assert.equal(b.facilities.find(f => f.id === 'public').level, 0, 'repair never constructs a well or a new facility level');
function quote(s, period) { const v = R.view(R.opening([]), [], s); return R.quote({ ...v, period }, { desk: 'place', contract: 'local' }, s); }
for (const period of [1, 2, 4]) assert.equal(quote(a, period).deliverable, quote(b, period).deliverable, 'repair is not an all-season sales perk');
const rainBefore = quote(a, 3), rainAfter = quote(b, 3);
assert.equal(rainBefore.deliverable, 18); assert.equal(rainAfter.deliverable, 21);
assert.equal(rainBefore.goodsCost, rainAfter.goodsCost);
assert.equal(rainAfter.revenue - rainBefore.revenue, 3000);
const oldLevels = JSON.stringify(p.island);
const ready = { ...a, scouted: ['raiou', 'fugaku', 'glaze', 'poro', 'yomi', 'souten', 'phenix', 'goka'] };
let book = F.open(F.restore({}), ready, 19);
assert.equal(F.view(book).care, null);
const frozen = JSON.stringify(book.active.snapshot);
assert.equal(F.view(F.restore({ shingan: { festival: book } })).care, null);
assert.equal(JSON.stringify(book.active.snapshot), frozen, 'a later repair cannot retroactively improve a public notice');
assert.equal(JSON.stringify(p.island), oldLevels);
console.log('PASS 300-coin genuine field repair: remaining155, no duplicate/unfunded/imaginary purchase, facility levels unchanged, rainy delivery18→21, other seasons unchanged and public notice frozen');
